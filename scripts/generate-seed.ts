/**
 * Generates supabase/seed.sql from the TypeScript sample content, so the SQL seed, the unit tests and the
 * publish-time solvability check all share one source of truth.
 *
 *   npm run seed:generate
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_BLOCKS } from '../supabase/functions/_shared/engine/commands.ts';
import { DEFAULT_SCORE_RULES } from '../supabase/functions/_shared/engine/scoring.ts';
import { SAMPLE_LEVELS } from '../supabase/functions/_shared/engine/sample-levels.ts';
import { buildSnapshot } from '../supabase/functions/_shared/engine/snapshot.ts';
import type { DraftData } from '../supabase/functions/_shared/engine/rows.ts';
import { SEED_LESSONS, SEED_REWARDS, SEED_ROBOTS, SEED_SCENES, SEED_WORLDS } from '../supabase/seed/content.ts';

const here = dirname(fileURLToPath(import.meta.url));

const uid = (kind: number, n: number) =>
  `${kind.toString(16).padStart(8, '0')}-0000-4000-8000-${n.toString(16).padStart(12, '0')}`;
const q = (s: string | null | undefined) => (s == null ? 'null' : `'${s.replace(/'/g, "''")}'`);
const j = (o: unknown) => `'${JSON.stringify(o).replace(/'/g, "''")}'::jsonb`;
const now = new Date().toISOString();
const ts = { created_at: now, updated_at: now };

// ---- build draft rows -------------------------------------------------
const worlds = SEED_WORLDS.map((w, i) => ({ id: uid(1, i + 1), position: i + 1, ...w, is_active: true, ...ts }));
const scenes = SEED_SCENES.map((s, i) => ({
  id: uid(3, i + 1), name: s.name, kind: 'builtin' as const, theme: s.theme, image_url: null, width: 960, height: 540, parallax: [], is_active: true, ...ts,
}));
const robots = SEED_ROBOTS.map((r, i) => ({
  id: uid(4, i + 1), name: r.name, kind: 'builtin' as const, builtin_style: r.style, sprite_url: null, frame_width: null, frame_height: null,
  animations: {}, scale: 1, move_speed_ms: 450, primary_color: r.color, is_default: r.isDefault, is_active: true, ...ts,
}));
const blocks = DEFAULT_BLOCKS.map((b, i) => ({ id: uid(7, i + 1), ...b, ...ts }));

const levels = SAMPLE_LEVELS.map((l, i) => ({
  id: uid(2, i + 1),
  code: l.code,
  world_id: worlds[l.worldIndex].id,
  position: i + 1,
  difficulty: l.difficulty,
  max_score: l.max_score,
  time_limit_seconds: null,
  scene_asset_id: scenes[l.worldIndex].id,
  robot_asset_id: null,
  completion_animation: 'celebrate' as const,
  unlock: { type: 'PREVIOUS_LEVEL' as const },
  is_active: true,
  version: 1,
  ...ts,
}));
const levelTranslations = SAMPLE_LEVELS.flatMap((l, i) =>
  (['th', 'en'] as const).map((lang, k) => ({
    id: uid(9, (i + 1) * 10 + k), level_id: levels[i].id, lang, title: l.title[lang] ?? '', description: l.description[lang] ?? '', ...ts,
  })),
);
const missions = SAMPLE_LEVELS.map((l, i) => ({
  id: uid(10, i + 1), level_id: levels[i].id, map: l.mission.map, robot_start: l.mission.robot_start, objectives: l.mission.objectives,
  rules: l.mission.rules, expected_solutions: l.solutions, ...ts,
}));
const hints = SAMPLE_LEVELS.flatMap((l, i) =>
  l.hints.map((h, k) => ({ id: uid(8, (i + 1) * 10 + k), level_id: levels[i].id, position: k + 1, text: h, ...ts })),
);
const lessons = SEED_LESSONS.map((l, i) => ({
  id: uid(5, i + 1), position: i + 1, image_url: null, video_url: null, demo_program: l.demo, is_active: true, ...ts,
}));
const lessonTranslations = SEED_LESSONS.flatMap((l, i) =>
  (['th', 'en'] as const).map((lang, k) => ({
    id: uid(11, (i + 1) * 10 + k), lesson_id: lessons[i].id, lang, title: l.title[lang] ?? '', summary: l.summary[lang] ?? '', body: l.body[lang] ?? '', ...ts,
  })),
);

const draft: DraftData = {
  settings: {
    score_rules: DEFAULT_SCORE_RULES, timer_enabled: true, total_duration_seconds: 1200, lesson_timer_seconds: null, level_timer_seconds: null,
    bonus_seconds_per_level: 0, lessons_mandatory: true, allow_skip_lessons: false, rewards_enabled: true,
  },
  worlds, levels, level_translations: levelTranslations, missions, hints, lessons, lesson_translations: lessonTranslations, blocks, robots, scenes,
};

const built = buildSnapshot(draft, 1, now);
if (!built.snapshot) {
  console.error('Seed content failed validation:\n' + built.errors.join('\n'));
  process.exit(1);
}

// ---- emit SQL -----------------------------------------------------------
const out: string[] = [];
const push = (s: string) => out.push(s);

push('-- GENERATED by scripts/generate-seed.ts — do not edit by hand. Run: npm run seed:generate');
push('-- Intended for an EMPTY database (supabase db reset runs it automatically).');
push('begin;');

push('insert into public.scene_assets (id, name, kind, theme, width, height, parallax) values');
push(scenes.map((s) => `  (${q(s.id)}, ${j(s.name)}, 'builtin', ${q(s.theme)}, 960, 540, '[]'::jsonb)`).join(',\n') + ';');

push('insert into public.robot_assets (id, name, kind, builtin_style, scale, move_speed_ms, primary_color, is_default) values');
push(robots.map((r) => `  (${q(r.id)}, ${j(r.name)}, 'builtin', ${q(r.builtin_style)}, 1, 450, ${q(r.primary_color)}, ${r.is_default})`).join(',\n') + ';');

push('insert into public.worlds (id, position, name, description, theme, color) values');
push(worlds.map((w) => `  (${q(w.id)}, ${w.position}, ${j(w.name)}, ${j(w.description)}, ${q(w.theme)}, ${q(w.color)})`).join(',\n') + ';');

push('insert into public.levels (id, code, world_id, position, difficulty, max_score, scene_asset_id, completion_animation, unlock, version) values');
push(levels.map((l) => `  (${q(l.id)}, ${q(l.code)}, ${q(l.world_id)}, ${l.position}, ${l.difficulty}, ${l.max_score}, ${q(l.scene_asset_id)}, 'celebrate', ${j(l.unlock)}, 1)`).join(',\n') + ';');

push('insert into public.level_translations (id, level_id, lang, title, description) values');
push(levelTranslations.map((t) => `  (${q(t.id)}, ${q(t.level_id)}, ${q(t.lang)}, ${q(t.title)}, ${q(t.description)})`).join(',\n') + ';');

push('insert into public.missions (id, level_id, map, robot_start, objectives, rules, expected_solutions) values');
push(missions.map((m) => `  (${q(m.id)}, ${q(m.level_id)}, ${j(m.map)}, ${j(m.robot_start)}, ${j(m.objectives)}, ${j(m.rules)}, ${j(m.expected_solutions)})`).join(',\n') + ';');

push('insert into public.hints (id, level_id, position, text) values');
push(hints.map((h) => `  (${q(h.id)}, ${q(h.level_id)}, ${h.position}, ${j(h.text)})`).join(',\n') + ';');

push('insert into public.lessons (id, position, demo_program) values');
push(lessons.map((l) => `  (${q(l.id)}, ${l.position}, ${l.demo_program ? j(l.demo_program) : 'null'})`).join(',\n') + ';');

push('insert into public.lesson_translations (id, lesson_id, lang, title, summary, body) values');
push(lessonTranslations.map((t) => `  (${q(t.id)}, ${q(t.lesson_id)}, ${q(t.lang)}, ${q(t.title)}, ${q(t.summary)}, ${q(t.body)})`).join(',\n') + ';');

push('insert into public.block_definitions (id, command_type, category, label, description, color, icon, params, enabled, position) values');
push(blocks.map((b) => `  (${q(b.id)}, ${q(b.command_type)}, ${q(b.category)}, ${j(b.label)}, ${j(b.description)}, ${q(b.color)}, ${q(b.icon)}, ${j(b.params)}, true, ${b.position})`).join(',\n') + ';');

push('insert into public.rewards (id, position, name, description, min_score, stock_total) values');
push(SEED_REWARDS.map((r, i) => `  (${q(uid(6, i + 1))}, ${i + 1}, ${j(r.name)}, ${j(r.description)}, ${r.min_score}, ${r.stock})`).join(',\n') + ';');

push(`insert into public.game_settings (score_rules, rewards_enabled) values (${j(DEFAULT_SCORE_RULES)}, true) on conflict (singleton) do nothing;`);
push('insert into public.dashboard_settings default values on conflict (singleton) do nothing;');
push(`insert into public.game_sessions (name, status, registration_open) values ('Open House', 'ACTIVE', true);`);
push(`insert into public.published_configs (snapshot, note) values (${j(built.snapshot)}, 'Initial seed configuration');`);
push('commit;');

const target = resolve(here, '../supabase/seed.sql');
writeFileSync(target, out.join('\n') + '\n', 'utf8');
console.log(`Wrote ${target} (${built.warnings.length} warnings)`);
